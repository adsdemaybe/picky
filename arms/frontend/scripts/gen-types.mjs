// Generates the gateway TypeScript types (never hand-write these, CLAUDE.md §7):
//   schemas/openapi.json       → src/lib/gateway/api-types.ts  (openapi-typescript: paths, components["schemas"])
//   schemas/events.schema.json → src/lib/gateway/events.ts     (json-schema-to-typescript: GatewayEvent union on "type")
//
// Sources, first match wins:
//   pnpm gen-types --url http://127.0.0.1:8000   fetch /openapi.json + /api/_schema/events from a running gateway
//   GATEWAY_URL=… pnpm gen-types                  same
//   pnpm gen-types --live                         same, using NEXT_PUBLIC_GATEWAY_URL (env or .env.local)
//   pnpm gen-types                                read schemas/*.json (written by `make gen-types` at the repo root)
// A fetched schema is also written to schemas/ so the committed inputs always match the generated files.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";
import openapiTS, { astToString } from "openapi-typescript";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const schemaDir = join(root, "schemas");
const outDir = join(root, "src", "lib", "gateway");
const args = process.argv.slice(2);

function envLocal(key) {
  try {
    const line = readFileSync(join(root, ".env.local"), "utf8")
      .split("\n")
      .find((l) => l.trim().startsWith(`${key}=`));
    return line ? line.split("=").slice(1).join("=").trim() : "";
  } catch {
    return "";
  }
}

function gatewayUrl() {
  const i = args.indexOf("--url");
  if (i >= 0 && args[i + 1]) return args[i + 1];
  if (process.env.GATEWAY_URL) return process.env.GATEWAY_URL;
  if (args.includes("--live")) return process.env.NEXT_PUBLIC_GATEWAY_URL || envLocal("NEXT_PUBLIC_GATEWAY_URL");
  return "";
}

async function getJson(url) {
  const r = await fetch(url, { signal: AbortSignal.timeout(10_000) });
  if (!r.ok) throw new Error(`${url} → HTTP ${r.status}`);
  return r.json();
}

async function loadSchemas() {
  const url = gatewayUrl().replace(/\/$/, "");
  if (url) {
    const [openapi, events] = await Promise.all([getJson(`${url}/openapi.json`), getJson(`${url}/api/_schema/events`)]);
    mkdirSync(schemaDir, { recursive: true });
    // same layout as `make gen-types` (python json.dumps indent=2, sort_keys) so the two paths don't churn
    writeFileSync(join(schemaDir, "openapi.json"), JSON.stringify(sortKeys(openapi), null, 2) + "\n");
    writeFileSync(join(schemaDir, "events.schema.json"), JSON.stringify(sortKeys(events), null, 2) + "\n");
    console.log(`gen-types: fetched schemas from ${url}`);
  }
  const files = ["openapi.json", "events.schema.json"].map((f) => join(schemaDir, f));
  const missing = files.filter((f) => !existsSync(f));
  if (missing.length) {
    console.error(`Missing ${missing.join(", ")}.\nRun \`make gen-types\` at the repo root, or \`pnpm gen-types --url http://localhost:8000\` against a running gateway.`);
    process.exit(1);
  }
  const [openapi, events] = files.map((f) => JSON.parse(readFileSync(f, "utf8")));
  return { openapi, events };
}

function sortKeys(v) {
  if (Array.isArray(v)) return v.map(sortKeys);
  if (!v || typeof v !== "object") return v;
  return Object.fromEntries(Object.keys(v).sort().map((k) => [k, sortKeys(v[k])]));
}

// pydantic puts a `title` on every field; json2ts turns each into an alias (Sku1, TripId2, …). Keep only the
// titles of the $defs roots (the contract model names) and of object schemas.
function stripTitles(node, isDefRoot) {
  if (Array.isArray(node)) return node.forEach((n) => stripTitles(n, false));
  if (!node || typeof node !== "object") return;
  if (!isDefRoot && "title" in node && !("properties" in node && node.type === "object")) delete node.title;
  for (const [k, v] of Object.entries(node)) {
    if (k === "$defs" || k === "definitions") for (const d of Object.values(v)) stripTitles(d, true);
    // a properties map is keyed by field name (a field may be called "title"): recurse into its schemas only
    else if (k === "properties" || k === "patternProperties") for (const d of Object.values(v)) stripTitles(d, false);
    else stripTitles(v, false);
  }
}

const { openapi, events } = await loadSchemas();
const version = openapi.info?.version ?? "?";
const banner = `/* GENERATED by scripts/gen-types.mjs from schemas/openapi.json + schemas/events.schema.json (contracts ${version}). Do not edit: run \`pnpm gen-types\`. */\n/* eslint-disable */\n`;
mkdirSync(outDir, { recursive: true });

const api = astToString(await openapiTS(openapi));
writeFileSync(join(outDir, "api-types.ts"), banner + api);

const ev = structuredClone(events);
stripTitles(ev, true);
ev.title = "GatewayEvent";
const evTs = await compile(ev, "GatewayEvent", { additionalProperties: false, bannerComment: "", unreachableDefinitions: false });
writeFileSync(join(outDir, "events.ts"), banner + evTs);

console.log(`gen-types: contracts ${version} → src/lib/gateway/api-types.ts, src/lib/gateway/events.ts`);
