"""Generate Cursor rules from CLAUDE.md and the arm READMEs.

CLAUDE.md is the single source of truth for AI-assistant rules (Claude Code reads it directly).
Cursor reads .cursor/rules/*.mdc, so this script mirrors:
  CLAUDE.md                -> .cursor/rules/picky.mdc        (always applied)
  arms/<arm>/README.md     -> .cursor/rules/arm-<arm>.mdc    (auto-attached when editing arms/<arm>/**)

Usage:
  python scripts/sync_agent_rules.py           # write files
  python scripts/sync_agent_rules.py --check   # exit 1 if any generated file is stale (used in CI)
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RULES_DIR = ROOT / ".cursor" / "rules"
HEADER = "<!-- GENERATED by scripts/sync_agent_rules.py from {src}. Edit {src}, then run `make rules`. -->\n\n"


def _mdc(description: str, body: str, src: str, globs: str = "", always_apply: bool = False) -> str:
    frontmatter = f'---\ndescription: "{description}"\nglobs: {globs}\nalwaysApply: {str(always_apply).lower()}\n---\n'
    return frontmatter + HEADER.format(src=src) + body


def expected_files() -> dict[Path, str]:
    files = {
        RULES_DIR / "picky.mdc": _mdc(
            "Picky project rules: pipeline, arms, git workflow, demo-ready bar, conventions",
            (ROOT / "CLAUDE.md").read_text(),
            "CLAUDE.md",
            always_apply=True,
        )
    }
    for readme in sorted((ROOT / "arms").glob("*/README.md")):
        arm = readme.parent.name
        files[RULES_DIR / f"arm-{arm}.mdc"] = _mdc(
            f"Scope, contract and demo-ready checklist for the {arm} arm",
            readme.read_text(),
            f"arms/{arm}/README.md",
            globs=f"arms/{arm}/**",
        )
    return files


def main() -> int:
    check = "--check" in sys.argv
    expected = expected_files()
    stale = [p for p, text in expected.items() if not p.exists() or p.read_text() != text]
    orphans = [p for p in RULES_DIR.glob("arm-*.mdc") if p not in expected] if RULES_DIR.exists() else []

    if check:
        for p in stale + orphans:
            print(f"stale: {p.relative_to(ROOT)}")
        if stale or orphans:
            print("Cursor rules are out of sync with CLAUDE.md / arm READMEs. Run `make rules`.")
            return 1
        return 0

    RULES_DIR.mkdir(parents=True, exist_ok=True)
    for p in stale:
        p.write_text(expected[p])
        print(f"wrote {p.relative_to(ROOT)}")
    for p in orphans:
        p.unlink()
        print(f"removed {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
